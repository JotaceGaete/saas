-- POS cancellation is distinct from voiding a payment.
-- Execute after reviewing in staging; no existing sales are changed by this migration.
CREATE OR REPLACE FUNCTION public.crm_cancel_pos_sale(
  p_invoice_id uuid,
  p_reason text
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $$
DECLARE
  v_invoice public.crm_invoices%ROWTYPE;
  v_user uuid := auth.uid();
  v_item record;
  v_label text;
BEGIN
  IF v_user IS NULL THEN RAISE EXCEPTION 'NOT_AUTHENTICATED'; END IF;
  IF length(btrim(coalesce(p_reason,''))) < 3 THEN
    RAISE EXCEPTION 'CANCELLATION_REASON_REQUIRED';
  END IF;
  SELECT i.* INTO v_invoice
  FROM public.crm_invoices i
  JOIN public.wa_businesses b ON b.id=i.business_id
  WHERE i.id=p_invoice_id AND b.user_id=v_user
  FOR UPDATE OF i;
  IF NOT FOUND THEN RAISE EXCEPTION 'SALE_NOT_FOUND_OR_FORBIDDEN'; END IF;
  IF v_invoice.source IS DISTINCT FROM 'pos' THEN
    RAISE EXCEPTION 'ONLY_POS_SALES_SUPPORTED';
  END IF;
  IF v_invoice.status='anulada' THEN
    RETURN jsonb_build_object('invoice_id',v_invoice.id,'already_cancelled',true);
  END IF;
  -- A locally voided payment does not refund a card charge.
  IF EXISTS (
    SELECT 1 FROM public.crm_pos_point_operations o
    WHERE o.crm_invoice_id=v_invoice.id
      AND o.mp_status='processed'
  ) THEN RAISE EXCEPTION 'POINT_REFUND_REQUIRED'; END IF;
  v_label := '(invoice ' || v_invoice.id::text || ')';
  -- Reverse only stock movements actually generated by the original POS sale,
  -- not all invoice items (non-stock products never generated a salida).
  FOR v_item IN
    SELECT m.product_id, SUM(m.quantity)::integer AS qty
    FROM public.crm_stock_movements m
    WHERE m.business_id=v_invoice.business_id
      AND m.type='salida'
      AND m.notes LIKE '%Venta TPV -- %' || v_label || '%'
    GROUP BY m.product_id
  LOOP
    INSERT INTO public.crm_stock_movements
      (business_id,product_id,type,quantity,notes,created_by)
    VALUES (v_invoice.business_id,v_item.product_id,'entrada',v_item.qty,
      'Cancelación TPV (invoice ' || v_invoice.id || '): ' || btrim(p_reason),v_user);
  END LOOP;
  UPDATE public.crm_payments
  SET voided_at=now(),voided_by=v_user,void_reason=btrim(p_reason)
  WHERE invoice_id=v_invoice.id AND voided_at IS NULL;
  UPDATE public.crm_invoices
  SET status='anulada',paid_at=NULL,
      notes=concat_ws(E'\\n',nullif(notes,''),'Anulación TPV: '||btrim(p_reason)),
      updated_at=now()
  WHERE id=v_invoice.id;
  RETURN jsonb_build_object('invoice_id',v_invoice.id,'already_cancelled',false);
END;
$$;
REVOKE ALL ON FUNCTION public.crm_cancel_pos_sale(uuid,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.crm_cancel_pos_sale(uuid,text) TO authenticated;

-- Database enforcement: client-side guards alone can be bypassed.
CREATE OR REPLACE FUNCTION public.crm_guard_point_payment_void()
RETURNS trigger LANGUAGE plpgsql SET search_path TO 'public' AS $$
BEGIN
  IF OLD.voided_at IS NULL AND NEW.voided_at IS NOT NULL
    AND EXISTS (
      SELECT 1 FROM public.crm_pos_point_operations o
      WHERE o.crm_invoice_id=OLD.invoice_id AND o.mp_status='processed'
    )
  THEN
    RAISE EXCEPTION 'POINT_REFUND_REQUIRED: No se puede anular en caja un cobro Point acreditado sin devolución.';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS crm_guard_point_payment_void_trigger ON public.crm_payments;
CREATE TRIGGER crm_guard_point_payment_void_trigger
BEFORE UPDATE OF voided_at ON public.crm_payments
FOR EACH ROW EXECUTE FUNCTION public.crm_guard_point_payment_void();
